function scopeCss(css, scope) {
  const chunks = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < css.length; i++) {
    if (css[i] === '{') depth++;
    if (css[i] === '}') {
      depth--;
      if (depth === 0) {
        chunks.push(css.slice(start, i + 1));
        start = i + 1;
      }
    }
  }
  return chunks
    .map((chunk) => {
      const m = chunk.match(/^([\s\S]*?)\{([\s\S]*)\}$/);
      if (!m) return '';
      const prelude = m[1].trim();
      const body = m[2];
      if (!prelude) return '';
      if (prelude.startsWith('@media')) {
        return `${prelude}{${scopeCss(body, scope)}}`;
      }
      if (prelude.startsWith('@')) return chunk;
      if (/\.(layout|sidebar)\b/.test(prelude) || prelude.includes('.back')) return '';
      const scopedPrelude = prelude
        .split(',')
        .map((sel) => {
          sel = sel.trim();
          if (!sel) return '';
          if (sel === 'body' || sel.startsWith('body ') || sel === '*') return '';
          if (sel.startsWith(scope)) return sel;
          return `${scope} ${sel}`;
        })
        .filter(Boolean)
        .join(', ');
      if (!scopedPrelude) return '';
      return `${scopedPrelude}{${body}}`;
    })
    .filter(Boolean)
    .join('\n');
}

